import { jsPDF } from 'jspdf';
import { DocumentRecord } from '../types/document';

/**
 * Generates an ID Card PDF layout:
 * Lays out Page 1 (Front) and Page 2 (Back) centered together onto a single portrait A4 sheet.
 */
export async function generateIdCardPdf(doc: DocumentRecord): Promise<File> {
  const pdf = new jsPDF({
    orientation: 'portrait',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = pdf.internal.pageSize.getWidth();
  const pageHeight = pdf.internal.pageSize.getHeight();

  // Document Title Header
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(16);
  pdf.setTextColor(30, 30, 35);
  pdf.text('IDENTIFICATION DOCUMENT', pageWidth / 2, 45, { align: 'center' });

  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(10);
  pdf.setTextColor(110, 110, 120);
  pdf.text(`${doc.name} • Scanned with Phantom Scanner`, pageWidth / 2, 62, { align: 'center' });

  // Draw separator line
  pdf.setDrawColor(220, 220, 230);
  pdf.setLineWidth(1);
  pdf.line(50, 75, pageWidth - 50, 75);

  const frontPage = doc.pages[0];
  const backPage = doc.pages[1] || doc.pages[0];

  // ID Card standard proportions (~85.6mm x 53.98mm, ratio 1.586)
  // On A4 in pt: width ~380pt, height ~240pt
  const cardW = 380;
  const cardH = 240;
  const cardX = (pageWidth - cardW) / 2;

  // Front slot
  const frontY = 100;
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(10);
  pdf.setTextColor(88, 86, 214); // Indigo
  pdf.text('FRONT SIDE', cardX, frontY - 8);

  // Border frame
  pdf.setDrawColor(200, 200, 210);
  pdf.roundedRect(cardX - 4, frontY - 4, cardW + 8, cardH + 8, 8, 8);

  if (frontPage) {
    try {
      pdf.addImage(frontPage.dataUrl, 'JPEG', cardX, frontY, cardW, cardH, undefined, 'FAST', frontPage.rotation || 0);
    } catch {
      pdf.text('[Front Side Image]', cardX + cardW / 2, frontY + cardH / 2, { align: 'center' });
    }
  }

  // Back slot
  const backY = 400;
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(10);
  pdf.setTextColor(88, 86, 214);
  pdf.text(doc.pages.length > 1 ? 'BACK SIDE' : 'BACK SIDE (REVERSED / BLANK)', cardX, backY - 8);

  pdf.setDrawColor(200, 200, 210);
  pdf.roundedRect(cardX - 4, backY - 4, cardW + 8, cardH + 8, 8, 8);

  if (backPage) {
    try {
      pdf.addImage(backPage.dataUrl, 'JPEG', cardX, backY, cardW, cardH, undefined, 'FAST', backPage.rotation || 0);
    } catch {
      pdf.text('[Back Side Image]', cardX + cardW / 2, backY + cardH / 2, { align: 'center' });
    }
  }

  // Footer
  pdf.setFontSize(8);
  pdf.setTextColor(140, 140, 150);
  const now = new Date().toLocaleDateString(undefined, { year: 'numeric', month: 'short', day: 'numeric' });
  pdf.text(`Generated on ${now} • Official 2-Sided Copy`, pageWidth / 2, pageHeight - 35, { align: 'center' });

  const blob = pdf.output('blob');
  const fileName = `${doc.name.replace(/[/\\?%*:|"<>]/g, '_')}_ID_Card_2in1.pdf`;
  return new File([blob], fileName, { type: 'application/pdf' });
}

export async function shareOrDownloadIdCardPdf(doc: DocumentRecord): Promise<void> {
  const file = await generateIdCardPdf(doc);

  if (navigator.canShare && navigator.canShare({ files: [file] })) {
    try {
      await navigator.share({
        files: [file],
        title: `${doc.name} - ID Card PDF`,
        text: 'Two-sided ID Card generated by Phantom Scanner',
      });
      return;
    } catch (e: unknown) {
      if ((e as Error)?.name === 'AbortError') return;
    }
  }

  const url = URL.createObjectURL(file);
  const a = document.createElement('a');
  a.href = url;
  a.download = file.name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
